function renderCart() {
  cartCount.textContent = cart.reduce((sum, item) => sum + item.qty, 0);
  if (!cart.length) {
    cartItems.innerHTML = `<p>${t("emptyCart")}</p>`;
  } else {
    cartItems.innerHTML = cart.map((item) => {
      const product = products.find((entry) => String(entry.id) === String(item.id));
      return `
        <div class="cart-item">
          <img src="${product.image || productImages[product.category]}" alt="" width="64" height="82" />
          <div>
            <strong>${product.label[currentLang]}</strong>
            <span class="cart-size">${t("size")}: <b dir="ltr">${item.size || "M"}</b></span>
            <small>${item.qty} × ${product.price} MAD</small>
          </div>
          <button class="icon-button" type="button" data-remove="${item.id}" data-remove-size="${item.size || "M"}" aria-label="${t("remove")} ${product.label[currentLang]}">×</button>
        </div>
      `;
    }).join("");
  }
  const total = cart.reduce((sum, item) => {
    const product = products.find((entry) => String(entry.id) === String(item.id));
    return sum + product.price * item.qty;
  }, 0);
  cartTotal.textContent = `${total} MAD`;
  document.querySelector('#checkoutForm button[type="submit"]').disabled = cart.length === 0;
}

let cartReturnFocus = null;

function openCart() {
  if (!cartPanel.classList.contains("open")) cartReturnFocus = document.activeElement;
  cartPanel.inert = false;
  document.body.classList.add("cart-open");
  document.querySelector(".cart-toggle").setAttribute("aria-expanded", "true");
  cartPanel.classList.add("open");
  overlay.classList.add("show");
  cartPanel.setAttribute("aria-hidden", "false");
  document.getElementById("closeCart").focus();
}

function closeCart() {
  cartPanel.classList.remove("open");
  overlay.classList.remove("show");
  cartPanel.setAttribute("aria-hidden", "true");
  cartPanel.inert = true;
  document.body.classList.remove("cart-open");
  document.querySelector(".cart-toggle").setAttribute("aria-expanded", "false");
  if (cartReturnFocus?.isConnected) cartReturnFocus.focus();
  else document.querySelector(".cart-toggle").focus();
}

document.addEventListener("click", (event) => {
  const addButton = event.target.closest("[data-add]");
  if (addButton) {
    successMessage.classList.remove("show");
    const id = addButton.dataset.add;
    const product = products.find((item) => String(item.id) === String(id));
    if (!product) return;
    const size = addButton.dataset.size || (product.category === "accessories" ? "42" : "M");
    const existing = cart.find((item) => String(item.id) === String(id) && item.size === size);
    if (existing) existing.qty += 1;
    else cart.push({ id, size, qty: 1 });
    renderCart();
    openCart();
  }

  const removeButton = event.target.closest("[data-remove]");
  if (removeButton) {
    const id = removeButton.dataset.remove;
    const size = removeButton.dataset.removeSize;
    cart = cart.filter((item) => !(String(item.id) === String(id) && (item.size || "M") === size));
    renderCart();
  }

  const filterButton = event.target.closest("[data-category]");
  if (filterButton) {
    activeCategory = filterButton.dataset.category;
    renderFilters();
    renderProducts();
  }

  const blogLink = event.target.closest("[data-blog-category]");
  if (blogLink) {
    activeCategory = blogLink.dataset.blogCategory;
    renderFilters();
    renderProducts();
  }
});

