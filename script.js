document.getElementById("checkoutForm").addEventListener("submit", async (event) => {
  event.preventDefault();
  if (!cart.length) return;
  const formData = new FormData(event.target);
  const total = cart.reduce((sum, item) => {
    const product = products.find((entry) => String(entry.id) === String(item.id));
    return sum + product.price * item.qty;
  }, 0);
  const orders = JSON.parse(localStorage.getItem("alwatin-orders") || "[]");
  orders.unshift({
    id: `AW-${Date.now().toString().slice(-6)}`,
    createdAt: new Date().toISOString(),
    customer: { name: formData.get("name"), phone: formData.get("phone"), address: formData.get("address") },
    items: cart.map((item) => ({ ...item })),
    total,
    status: "new",
    language: currentLang,
    payment: "cod"
  });
  localStorage.setItem("alwatin-orders", JSON.stringify(orders.slice(0, 200)));
  if (window.AlwatinDB) {
    try {
      await AlwatinDB.rpc("place_order", {
        customer_name: formData.get("name"),
        customer_phone: formData.get("phone"),
        customer_address: formData.get("address"),
        order_language: currentLang,
        order_items: cart.map(item => { const product = products.find(entry => String(entry.id) === String(item.id)); return { product_id: /^[0-9a-f-]{36}$/i.test(String(product.id)) ? product.id : null, product_name: product.label[currentLang], product_image: product.image || productImages[product.category], size: item.size || "M", quantity: item.qty, unit_price: product.price }; })
      });
    } catch (error) {
      console.warn("Supabase order sync failed; local order retained.", error);
    }
  }
  if (successModal?.showModal) successModal.showModal();
  else successModal?.setAttribute("open", "");
  cart = [];
  renderCart();
  event.target.reset();
});

document.addEventListener("keydown", (event) => {
  if (!cartPanel.classList.contains("open")) return;
  if (event.key === "Escape") closeCart();
  if (event.key === "Tab") {
    const controls = [...cartPanel.querySelectorAll('button:not(:disabled), input, textarea, a[href]')];
    const first = controls[0];
    const last = controls[controls.length - 1];
    if (event.shiftKey && document.activeElement === first) { event.preventDefault(); last.focus(); }
    else if (!event.shiftKey && document.activeElement === last) { event.preventDefault(); first.focus(); }
  }
});

async function loadStoreSettings() {
  if (!window.AlwatinDB) return;
  try {
    const rows = await AlwatinDB.select("store_settings", "?select=whatsapp&id=eq.true&limit=1");
    if (rows[0]?.whatsapp) {
      window.ALWATIN_SUPABASE.whatsapp = rows[0].whatsapp;
      updateWhatsAppSupportLink();
    }
  } catch { /* Keep the fallback contact link when settings are unavailable. */ }
}

updateWhatsAppSupportLink();
loadStoreSettings();
