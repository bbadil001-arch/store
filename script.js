function renderCart() {
  cartCount.textContent = cart.reduce((sum, item) => sum + item.qty, 0);
  if (bottomCartCount) bottomCartCount.textContent = cart.reduce((sum, item) => sum + item.qty, 0);
  if (!cart.length) {
    cartItems.innerHTML = `<p>${t("emptyCart")}</p>`;
  } else {
    cartItems.innerHTML = cart.map((item) => {
      const product = products.find((entry) => String(entry.id) === String(item.id));
      return `
        <div class="cart-item">
          <img src="${product.image || productImages[product.category]}" alt="" width="64" height="82" />
          <div>
            <strong>${product.label[currentLang]}</strong>
            <span class="cart-size">${t("size")}: <b dir="ltr">${item.size || "M"}</b></span>
            <small>${item.qty} × ${product.price} MAD</small>
          </div>
          <button class="icon-button" type="button" data-remove="${item.id}" data-remove-size="${item.size || "M"}" aria-label="${t("remove")} ${product.label[currentLang]}">×</button>
        </div>
      `;
    }).join("");
  }
  const total = cart.reduce((sum, item) => {
    const product = products.find((entry) => String(entry.id) === String(item.id));
    return sum + product.price * item.qty;
  }, 0);
  cartTotal.textContent = `${total} MAD`;
  document.querySelector('#checkoutForm button[type="submit"]').disabled = cart.length === 0;
}

