function t(key) {
  return translations[currentLang][key] || key;
}

function applyLanguage(lang) {
  currentLang = translations[lang] ? lang : "ar";
  lang = currentLang;
  languageSelect.value = lang;
  if (mobileLanguageSelect) mobileLanguageSelect.value = lang;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.body.dir = lang === "ar" ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-label]").forEach((node) => node.setAttribute("aria-label", t(node.dataset.i18nLabel)));
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder)));
  document.title = `${t("brand")} | Alwatin — ${t("brandSub")}`;
  renderFilters();
  renderProducts();
  renderBlog();
  renderCart();
  updateWhatsAppSupportLink();
  if (typeof renderProductPage === "function") renderProductPage();
}

function renderFilters() {
  categoryFilters.innerHTML = categories.map((category) => `
    <a class="filter-chip ${category === activeCategory ? "active" : ""}" href="${categoryPageLinks[category]}" data-category="${category}" aria-pressed="${category === activeCategory}">
      <img src="${productImages[category]}" alt="" width="240" height="300" loading="lazy" />
      <span>${categoryLabels[currentLang][category]}</span>
    </a>`).join("");
  document.querySelectorAll('[data-category="all"]').forEach((node) => {
    if (node.tagName === "BUTTON") node.setAttribute("aria-pressed", String(activeCategory === "all"));
  });
  requestAnimationFrame(updateCategoryCarousel);
}

function updateCategoryCarousel() {
  if (!categoryFilters || !categoryPrev || !categoryNext) return;
  const maxScroll = Math.max(0, categoryFilters.scrollWidth - categoryFilters.clientWidth);
  const direction = getComputedStyle(categoryFilters).direction;
  const position = direction === "rtl" ? Math.abs(categoryFilters.scrollLeft) : categoryFilters.scrollLeft;
  categoryPrev.disabled = maxScroll <= 2 || position <= 2;
  categoryNext.disabled = maxScroll <= 2 || position >= maxScroll - 2;
}

function scrollCategoryCarousel(step) {
  if (!categoryFilters) return;
  const distance = Math.max(categoryFilters.clientWidth * .92, 220);
  const direction = getComputedStyle(categoryFilters).direction === "rtl" ? -1 : 1;
  categoryFilters.scrollBy({ left: step * distance * direction, behavior: "smooth" });
}

function savedFavouriteIds() {
  try {
    const value = JSON.parse(localStorage.getItem("alwatin-favourites") || "[]");
    return new Set(Array.isArray(value) ? value.map(String) : []);
  } catch {
    return new Set();
  }
}

function toggleFavourite(id) {
  const saved = savedFavouriteIds();
  const key = String(id);
  if (saved.has(key)) saved.delete(key);
  else saved.add(key);
  localStorage.setItem("alwatin-favourites", JSON.stringify([...saved]));
  renderProducts();
}

